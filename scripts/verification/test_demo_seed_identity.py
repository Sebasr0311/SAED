"""The demo seed inserts explicit primary keys; its identity resync block must cover every such table.

Without the resync a fresh install hands id 1 to the first application-created row of a seeded table and the
insert fails with ORA-00001 (seen as HTTP 409 on the first contract created through the API).
"""
import re
import unittest
from pathlib import Path

SEED = Path(__file__).resolve().parents[2] / "database" / "seeds" / "demo" / "V5.99__demo_seeds.sql"
# Catalog tables: the application never creates rows in them, so an unsynchronised identity cannot collide.
CATALOGS = {"ROLES", "TIPOS_DOCUMENTO", "TIPOS_PROPIEDAD", "TIPOS_UNIDAD"}


class DemoSeedIdentityTest(unittest.TestCase):
    def test_every_table_seeded_with_an_explicit_key_resyncs_its_identity(self):
        source = SEED.read_text(encoding="utf-8")
        seeded = set(re.findall(r"^INSERT INTO (\w+) \(ID_\w+", source, re.M))
        resynced = set(re.findall(r"ALTER TABLE (\w+) MODIFY \(\w+ GENERATED BY DEFAULT ON NULL AS IDENTITY \(START WITH LIMIT VALUE\)\)", source))
        # RESIDENTES_UNIDAD is seeded by its natural columns (ID_UNIDAD, ...) and keeps a generated key.
        missing = sorted(seeded - resynced - CATALOGS - {"RESIDENTES_UNIDAD"})
        self.assertEqual([], missing, "seeded with explicit ids but identity not resynchronised: %s" % missing)


if __name__ == "__main__":
    unittest.main()
