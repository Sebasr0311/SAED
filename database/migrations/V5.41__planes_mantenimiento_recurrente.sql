-- =============================================================================
-- SAED 2.0 - V5.41: RECURRING MAINTENANCE PLANS
-- =============================================================================
-- Audit F9-12 (plan F09-01). PLANES_MANTENIMIENTO stores a property's recurring preventive plans.
-- PlanMantenimientoService.generarOrdenesProgramadas(property, date) creates the scheduled order of
-- the latest due period of every active plan in MANTENIMIENTOS, tagged with ID_PLAN_MANTENIMIENTO
-- and PERIODO_PLAN (ISO date of the occurrence). The unique index UQ_MANT_PLAN_PERIODO guarantees one
-- order per plan and period across replays, restarts and several application instances; manual
-- orders keep both columns NULL and are not indexed.
--
-- Idempotent: guarded by data-dictionary checks. Runs as a non-exempt owner under active VPD:
-- columns added to MANTENIMIENTOS are nullable without DEFAULT; defaults appear only in the
-- CREATE TABLE of the new table; no data is rewritten; any error aborts.

BEGIN
    PKG_SAED_SESSION.SET_BOOTSTRAP_CONTEXT(1);
    PKG_SAED_SESSION.SET_CONTEXT(1, 1, 1, 'SUPERADMIN');
END;
/

-- 1. Plans table
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'PLANES_MANTENIMIENTO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE PLANES_MANTENIMIENTO ('
            || 'ID_PLAN_MANTENIMIENTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, '
            || 'ID_PROPIEDAD NUMBER NOT NULL, '
            || 'ID_ACTIVO NUMBER, '
            || 'TITULO VARCHAR2(150 CHAR) NOT NULL, '
            || 'DESCRIPCION_TRABAJO VARCHAR2(2000 CHAR) NOT NULL, '
            || 'TIPO_MANTENIMIENTO VARCHAR2(20 CHAR) DEFAULT ''PREVENTIVO'' NOT NULL, '
            || 'PRIORIDAD VARCHAR2(15 CHAR) DEFAULT ''MEDIA'' NOT NULL, '
            || 'FRECUENCIA VARCHAR2(15 CHAR) NOT NULL, '
            || 'FECHA_INICIO DATE NOT NULL, '
            || 'COSTO_ESTIMADO NUMBER(12,2) DEFAULT 0 NOT NULL, '
            || 'ID_PROVEEDOR_SERVICIO NUMBER, '
            || 'ACTIVO CHAR(1 CHAR) DEFAULT ''S'' NOT NULL, '
            || 'CREADO_POR NUMBER, '
            || 'FECHA_CREACION TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, '
            || 'CONSTRAINT PK_PLANES_MANTENIMIENTO PRIMARY KEY (ID_PLAN_MANTENIMIENTO), '
            || 'CONSTRAINT FK_PLANMANT_PROPIEDAD FOREIGN KEY (ID_PROPIEDAD) REFERENCES PROPIEDADES (ID_PROPIEDAD), '
            || 'CONSTRAINT FK_PLANMANT_ACTIVO FOREIGN KEY (ID_ACTIVO) REFERENCES ACTIVOS (ID_ACTIVO), '
            || 'CONSTRAINT FK_PLANMANT_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR_SERVICIO) REFERENCES PROVEEDORES (ID_PROVEEDOR), '
            || 'CONSTRAINT CK_PLANMANT_FRECUENCIA CHECK (FRECUENCIA IN (''MENSUAL'',''BIMESTRAL'',''TRIMESTRAL'',''SEMESTRAL'',''ANUAL'')), '
            || 'CONSTRAINT CK_PLANMANT_TIPO CHECK (TIPO_MANTENIMIENTO IN (''PREVENTIVO'',''PREDICTIVO'',''LOCATIVO'')), '
            || 'CONSTRAINT CK_PLANMANT_PRIORIDAD CHECK (PRIORIDAD IN (''BAJA'',''MEDIA'',''ALTA'',''URGENTE'')), '
            || 'CONSTRAINT CK_PLANMANT_ACTIVO CHECK (ACTIVO IN (''S'',''N'')), '
            || 'CONSTRAINT CK_PLANMANT_COSTO CHECK (COSTO_ESTIMADO >= 0))';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_PLANMANT_PROP_ACTIVO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_PLANMANT_PROP_ACTIVO ON PLANES_MANTENIMIENTO (ID_PROPIEDAD, ACTIVO)';
    END IF;
END;
/

-- 2. Plan link on generated orders (nullable, no default)
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_TAB_COLS
    WHERE TABLE_NAME = 'MANTENIMIENTOS' AND COLUMN_NAME = 'ID_PLAN_MANTENIMIENTO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE MANTENIMIENTOS ADD (ID_PLAN_MANTENIMIENTO NUMBER)';
    END IF;

    SELECT COUNT(1) INTO v_count FROM USER_TAB_COLS
    WHERE TABLE_NAME = 'MANTENIMIENTOS' AND COLUMN_NAME = 'PERIODO_PLAN';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE MANTENIMIENTOS ADD (PERIODO_PLAN VARCHAR2(10 CHAR))';
    END IF;

    SELECT COUNT(1) INTO v_count FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'MANTENIMIENTOS' AND CONSTRAINT_NAME = 'FK_MANT_PLAN';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE MANTENIMIENTOS ADD CONSTRAINT FK_MANT_PLAN '
            || 'FOREIGN KEY (ID_PLAN_MANTENIMIENTO) REFERENCES PLANES_MANTENIMIENTO (ID_PLAN_MANTENIMIENTO)';
    END IF;
END;
/

-- 3. One order per plan and period (rows without a plan have an all-NULL key and are not indexed)
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_INDEXES
    WHERE TABLE_NAME = 'MANTENIMIENTOS' AND INDEX_NAME = 'UQ_MANT_PLAN_PERIODO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UQ_MANT_PLAN_PERIODO ON MANTENIMIENTOS (ID_PLAN_MANTENIMIENTO, PERIODO_PLAN)';
    END IF;
END;
/

-- 4. Tenant isolation for the new table
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_POLICIES
    WHERE OBJECT_NAME = 'PLANES_MANTENIMIENTO' AND POLICY_NAME = 'POL_RLS_PROP_PLANES_MANT';
    IF v_count = 0 THEN
        DBMS_RLS.ADD_POLICY(
            object_schema   => NULL,
            object_name     => 'PLANES_MANTENIMIENTO',
            policy_name     => 'POL_RLS_PROP_PLANES_MANT',
            function_schema => NULL,
            policy_function => 'PKG_SAED_SECURITY_RLS.FN_FILTRO_PROPIEDAD',
            statement_types => 'SELECT,INSERT,UPDATE,DELETE',
            update_check    => TRUE,
            enable          => TRUE
        );
    END IF;
END;
/
