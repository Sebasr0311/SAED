-- =============================================================================
-- SAED 2.0 - V5.42: SUPPLIER CONTRACT RENEWAL NOTICES
-- =============================================================================
-- Audit F9-10 (plan F09-02). AvisoRenovacionService.generarAvisos(property, date) records one notice
-- per VIGENTE supplier contract and end date (PERIODO_REFERENCIA = FECHA_FIN as ISO text) once the
-- contract's DIAS_ALERTA_VENC window opens, and raises an ALERTAS_ADMIN row in the same transaction.
-- UQ_AVISO_RENOV_PERIODO guarantees a single notice across retries, restarts and several instances;
-- renewing a contract (new end date) opens a new period.
--
-- Idempotent: guarded by data-dictionary checks. Only a new table is created (defaults allowed in
-- CREATE TABLE); no existing table is altered and no data is rewritten; any error aborts.

BEGIN
    PKG_SAED_SESSION.SET_BOOTSTRAP_CONTEXT(1);
    PKG_SAED_SESSION.SET_CONTEXT(1, 1, 1, 'SUPERADMIN');
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'AVISOS_RENOVACION_CONTRATO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE AVISOS_RENOVACION_CONTRATO ('
            || 'ID_AVISO_RENOVACION NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, '
            || 'ID_PROPIEDAD NUMBER NOT NULL, '
            || 'ID_CONTRATO_PROVEEDOR NUMBER NOT NULL, '
            || 'PERIODO_REFERENCIA VARCHAR2(10 CHAR) NOT NULL, '
            || 'FECHA_FIN DATE NOT NULL, '
            || 'FECHA_AVISO TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, '
            || 'CONSTRAINT PK_AVISOS_RENOVACION PRIMARY KEY (ID_AVISO_RENOVACION), '
            || 'CONSTRAINT FK_AVISORENOV_PROPIEDAD FOREIGN KEY (ID_PROPIEDAD) REFERENCES PROPIEDADES (ID_PROPIEDAD), '
            || 'CONSTRAINT FK_AVISORENOV_CONTRATO FOREIGN KEY (ID_CONTRATO_PROVEEDOR) '
            || 'REFERENCES CONTRATOS_PROVEEDOR (ID_CONTRATO_PROVEEDOR) ON DELETE CASCADE)';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_INDEXES
    WHERE TABLE_NAME = 'AVISOS_RENOVACION_CONTRATO' AND INDEX_NAME = 'UQ_AVISO_RENOV_PERIODO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UQ_AVISO_RENOV_PERIODO '
            || 'ON AVISOS_RENOVACION_CONTRATO (ID_CONTRATO_PROVEEDOR, PERIODO_REFERENCIA)';
    END IF;

    SELECT COUNT(1) INTO v_count FROM USER_INDEXES
    WHERE TABLE_NAME = 'AVISOS_RENOVACION_CONTRATO' AND INDEX_NAME = 'IX_AVISO_RENOV_PROP';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_AVISO_RENOV_PROP ON AVISOS_RENOVACION_CONTRATO (ID_PROPIEDAD)';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_POLICIES
    WHERE OBJECT_NAME = 'AVISOS_RENOVACION_CONTRATO' AND POLICY_NAME = 'POL_RLS_PROP_AVISOS_RENOV';
    IF v_count = 0 THEN
        DBMS_RLS.ADD_POLICY(
            object_schema   => NULL,
            object_name     => 'AVISOS_RENOVACION_CONTRATO',
            policy_name     => 'POL_RLS_PROP_AVISOS_RENOV',
            function_schema => NULL,
            policy_function => 'PKG_SAED_SECURITY_RLS.FN_FILTRO_PROPIEDAD',
            statement_types => 'SELECT,INSERT,UPDATE,DELETE',
            update_check    => TRUE,
            enable          => TRUE
        );
    END IF;
END;
/
