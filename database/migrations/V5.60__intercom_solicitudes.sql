-- =============================================================================
-- SAED 2.0 - V5.60: PERSISTED INTERCOM (CITOFONIA) REQUESTS
-- =============================================================================
-- F07-02. The gate asks the residents of a unit to approve or deny a visitor; the
-- request and the decision are persisted so that the gate reads the real decision
-- (no fixed "approved" answer), expiry/cancel are explicit states and a decision
-- can be taken only once (conditional update on ESTADO = 'PENDIENTE').
--
-- Idempotent; runs as a non-exempt owner under active VPD:
--   * new table with a property column and a FN_FILTRO_PROPIEDAD policy;
--   * index creation tolerates only ORA-01408;
--   * no blanket exception handlers.

BEGIN
    PKG_SAED_SESSION.SET_BOOTSTRAP_CONTEXT(1);
    PKG_SAED_SESSION.SET_CONTEXT(1, 1, 1, 'SUPERADMIN');
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'INTERCOM_SOLICITUDES';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE INTERCOM_SOLICITUDES (
                ID_SOLICITUD      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                ID_PROPIEDAD      NUMBER NOT NULL,
                ID_UNIDAD         NUMBER NOT NULL,
                ID_VISITA         NUMBER,
                SOLICITADO_POR    NUMBER NOT NULL,
                NOMBRE_VISITANTE  VARCHAR2(200 CHAR),
                ESTADO            VARCHAR2(20 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
                FECHA_SOLICITUD   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                FECHA_EXPIRACION  TIMESTAMP WITH TIME ZONE NOT NULL,
                RESPONDIDO_POR    NUMBER,
                FECHA_RESPUESTA   TIMESTAMP WITH TIME ZONE,
                CONSTRAINT PK_INTERCOM_SOLICITUDES PRIMARY KEY (ID_SOLICITUD),
                CONSTRAINT CK_INTERCOM_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'EXPIRADA', 'CANCELADA')),
                CONSTRAINT FK_INTERCOM_PROPIEDAD FOREIGN KEY (ID_PROPIEDAD) REFERENCES PROPIEDADES (ID_PROPIEDAD),
                CONSTRAINT FK_INTERCOM_UNIDAD FOREIGN KEY (ID_UNIDAD) REFERENCES UNIDADES (ID_UNIDAD),
                CONSTRAINT FK_INTERCOM_VISITA FOREIGN KEY (ID_VISITA) REFERENCES VISITAS (ID_VISITA),
                CONSTRAINT FK_INTERCOM_SOLICITANTE FOREIGN KEY (SOLICITADO_POR) REFERENCES USUARIOS (ID_USUARIO),
                CONSTRAINT FK_INTERCOM_RESPONDIO FOREIGN KEY (RESPONDIDO_POR) REFERENCES USUARIOS (ID_USUARIO)
            )
        ]';
    END IF;
END;
/

DECLARE
    PROCEDURE add_index(p_name IN VARCHAR2, p_ddl IN VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(1) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = p_name;
        IF v_count = 0 THEN
            BEGIN
                EXECUTE IMMEDIATE p_ddl;
            EXCEPTION
                WHEN OTHERS THEN
                    -- ORA-01408: an equivalent index already exists under another name.
                    IF SQLCODE != -1408 THEN
                        RAISE;
                    END IF;
            END;
        END IF;
    END;
BEGIN
    add_index('IX_INTERCOM_UNIDAD_ESTADO', 'CREATE INDEX IX_INTERCOM_UNIDAD_ESTADO ON INTERCOM_SOLICITUDES (ID_UNIDAD, ESTADO)');
    add_index('IX_INTERCOM_VISITA', 'CREATE INDEX IX_INTERCOM_VISITA ON INTERCOM_SOLICITUDES (ID_VISITA)');
    add_index('IX_INTERCOM_PROPIEDAD', 'CREATE INDEX IX_INTERCOM_PROPIEDAD ON INTERCOM_SOLICITUDES (ID_PROPIEDAD)');
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_POLICIES
    WHERE OBJECT_NAME = 'INTERCOM_SOLICITUDES' AND POLICY_NAME = 'POL_RLS_PROP_INTERCOM';
    IF v_count = 0 THEN
        DBMS_RLS.ADD_GROUPED_POLICY(
            object_schema   => NULL,
            object_name     => 'INTERCOM_SOLICITUDES',
            policy_group    => 'SYS_DEFAULT',
            policy_name     => 'POL_RLS_PROP_INTERCOM',
            function_schema => NULL,
            policy_function => 'PKG_SAED_SECURITY_RLS.FN_FILTRO_PROPIEDAD',
            statement_types => 'SELECT,INSERT,UPDATE,DELETE',
            update_check    => TRUE,
            enable          => TRUE,
            static_policy   => FALSE,
            policy_type     => DBMS_RLS.DYNAMIC,
            long_predicate  => FALSE
        );
    END IF;
END;
/

COMMIT;
