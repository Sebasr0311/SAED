-- SAED 2.0 - V5.51: PER-PROPERTY BILLING SETTINGS
-- =============================================================================
-- Audit F6-02 / plan F06-02, DEC-08.
-- CONFIGURACION_COBRO_PROPIEDAD holds the monthly-fee settings of one property: an optional fixed
-- fee that replaces the budget share by coefficient, the early-payment discount (percentage and
-- days) and the simple monthly late interest (percentage, optional ceiling and grace days). Discount
-- and interest default to 0 % (disabled); no legal rate is invented. BillingService reads the row and
-- falls back to the disabled defaults when a property has none.
--
-- Idempotent (data-dictionary checks). Runs as a non-exempt owner under active VPD. Defaults appear
-- only in CREATE TABLE of the new table; nothing existing is altered; any error aborts.

BEGIN
    PKG_SAED_SESSION.SET_BOOTSTRAP_CONTEXT(1);
    PKG_SAED_SESSION.SET_CONTEXT(1, 1, 1, 'SUPERADMIN');
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'CONFIGURACION_COBRO_PROPIEDAD';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE CONFIGURACION_COBRO_PROPIEDAD ('
            || 'ID_CONFIGURACION NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, '
            || 'ID_PROPIEDAD NUMBER NOT NULL, '
            || 'CUOTA_FIJA NUMBER(12,2), '
            || 'PORC_DESCUENTO_PRONTO_PAGO NUMBER(5,2) DEFAULT 0 NOT NULL, '
            || 'DIAS_PRONTO_PAGO NUMBER(3) DEFAULT 0 NOT NULL, '
            || 'PORC_INTERES_MORA_MENSUAL NUMBER(5,2) DEFAULT 0 NOT NULL, '
            || 'TOPE_INTERES_MORA_MENSUAL NUMBER(5,2), '
            || 'DIAS_GRACIA NUMBER(3) DEFAULT 0 NOT NULL, '
            || 'DIA_VENCIMIENTO NUMBER(2) DEFAULT 10 NOT NULL, '
            || 'FECHA_ACTUALIZACION DATE DEFAULT SYSDATE NOT NULL, '
            || 'CONSTRAINT PK_CONFIG_COBRO_PROP PRIMARY KEY (ID_CONFIGURACION), '
            || 'CONSTRAINT UQ_CONFIG_COBRO_PROP UNIQUE (ID_PROPIEDAD), '
            || 'CONSTRAINT FK_CONFIG_COBRO_PROP FOREIGN KEY (ID_PROPIEDAD) REFERENCES PROPIEDADES (ID_PROPIEDAD), '
            || 'CONSTRAINT CK_CONFIG_COBRO_FIJA CHECK (CUOTA_FIJA IS NULL OR CUOTA_FIJA >= 0), '
            || 'CONSTRAINT CK_CONFIG_COBRO_DESC CHECK (PORC_DESCUENTO_PRONTO_PAGO BETWEEN 0 AND 100), '
            || 'CONSTRAINT CK_CONFIG_COBRO_DIAS_PP CHECK (DIAS_PRONTO_PAGO BETWEEN 0 AND 31), '
            || 'CONSTRAINT CK_CONFIG_COBRO_INT CHECK (PORC_INTERES_MORA_MENSUAL BETWEEN 0 AND 100), '
            || 'CONSTRAINT CK_CONFIG_COBRO_TOPE CHECK (TOPE_INTERES_MORA_MENSUAL IS NULL OR TOPE_INTERES_MORA_MENSUAL BETWEEN 0 AND 100), '
            || 'CONSTRAINT CK_CONFIG_COBRO_GRACIA CHECK (DIAS_GRACIA BETWEEN 0 AND 365), '
            || 'CONSTRAINT CK_CONFIG_COBRO_DIA CHECK (DIA_VENCIMIENTO BETWEEN 1 AND 28))';
    END IF;
END;
/

-- Tenant isolation: the table has ID_PROPIEDAD, which FN_FILTRO_PROPIEDAD filters on.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_POLICIES
    WHERE OBJECT_NAME = 'CONFIGURACION_COBRO_PROPIEDAD' AND POLICY_NAME = 'POL_RLS_PROP_CONFIG_COBRO';
    IF v_count = 0 THEN
        DBMS_RLS.ADD_POLICY(
            object_schema   => NULL,
            object_name     => 'CONFIGURACION_COBRO_PROPIEDAD',
            policy_name     => 'POL_RLS_PROP_CONFIG_COBRO',
            function_schema => NULL,
            policy_function => 'PKG_SAED_SECURITY_RLS.FN_FILTRO_PROPIEDAD',
            statement_types => 'SELECT,INSERT,UPDATE,DELETE',
            update_check    => TRUE,
            enable          => TRUE
        );
    END IF;
END;
/
