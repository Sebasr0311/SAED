-- =============================================================================
-- SAED 2.0 - V5.62: PER-USER READ AND ARCHIVE STATE OF NOTICES
-- =============================================================================
-- F08-03. One row per (notice, user): LEIDO_EN when the user read it, ARCHIVADO_EN
-- when the user archived it for themselves. The state is shared by every session of
-- the user and drives the notice list and badge. ARCHIVADO on COMUNICADOS remains the
-- administration-wide archive.
--
-- Idempotent; runs as a non-exempt owner under active VPD:
--   * new table with a property column and a FN_FILTRO_PROPIEDAD policy;
--   * index creation tolerates only ORA-01408;
--   * no blanket exception handlers.

BEGIN
    PKG_SAED_SESSION.SET_BOOTSTRAP_CONTEXT(1);
    PKG_SAED_SESSION.SET_CONTEXT(1, 1, 1, 'SUPERADMIN');
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'COMUNICADOS_LECTURAS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE COMUNICADOS_LECTURAS (
                ID_LECTURA     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                ID_COMUNICADO  NUMBER NOT NULL,
                ID_USUARIO     NUMBER NOT NULL,
                ID_PROPIEDAD   NUMBER NOT NULL,
                LEIDO_EN       TIMESTAMP WITH TIME ZONE,
                ARCHIVADO_EN   TIMESTAMP WITH TIME ZONE,
                CONSTRAINT PK_COMUNICADOS_LECTURAS PRIMARY KEY (ID_LECTURA),
                CONSTRAINT UQ_COMUNICADO_LECTURA UNIQUE (ID_COMUNICADO, ID_USUARIO),
                CONSTRAINT FK_LECTURA_COMUNICADO FOREIGN KEY (ID_COMUNICADO) REFERENCES COMUNICADOS (ID_COMUNICADO),
                CONSTRAINT FK_LECTURA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO),
                CONSTRAINT FK_LECTURA_PROPIEDAD FOREIGN KEY (ID_PROPIEDAD) REFERENCES PROPIEDADES (ID_PROPIEDAD)
            )
        ]';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_LECTURA_USUARIO';
    IF v_count = 0 THEN
        BEGIN
            EXECUTE IMMEDIATE 'CREATE INDEX IX_LECTURA_USUARIO ON COMUNICADOS_LECTURAS (ID_USUARIO)';
        EXCEPTION
            WHEN OTHERS THEN
                -- ORA-01408: an equivalent index already exists under another name.
                IF SQLCODE != -1408 THEN
                    RAISE;
                END IF;
        END;
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO v_count FROM USER_POLICIES
    WHERE OBJECT_NAME = 'COMUNICADOS_LECTURAS' AND POLICY_NAME = 'POL_RLS_PROP_COM_LECTURAS';
    IF v_count = 0 THEN
        DBMS_RLS.ADD_GROUPED_POLICY(
            object_schema   => NULL,
            object_name     => 'COMUNICADOS_LECTURAS',
            policy_group    => 'SYS_DEFAULT',
            policy_name     => 'POL_RLS_PROP_COM_LECTURAS',
            function_schema => NULL,
            policy_function => 'PKG_SAED_SECURITY_RLS.FN_FILTRO_PROPIEDAD',
            statement_types => 'SELECT,INSERT,UPDATE,DELETE',
            update_check    => TRUE,
            enable          => TRUE,
            static_policy   => FALSE,
            policy_type     => DBMS_RLS.DYNAMIC,
            long_predicate  => FALSE
        );
    END IF;
END;
/

COMMIT;
